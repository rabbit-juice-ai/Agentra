/** recovery_locked / shutting_down 只允许这两个查询。 */
export const LOCKDOWN_READ_METHODS: ReadonlySet<string> = new Set([
  CORE_HEALTH_METHOD,
  CORE_MAINTENANCE_STATUS_METHOD,
])

export function isMaintenanceReadMethod(method: string): boolean {
  return MAINTENANCE_READ_METHODS.has(method)
}

export function isLockdownReadMethod(method: string): boolean {
  return LOCKDOWN_READ_METHODS.has(method)
}
