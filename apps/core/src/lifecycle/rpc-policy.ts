/**
 * 维护期间允许的只读 RPC 白名单。
 *
 * 这里的“只读”是安全边界，不是性能标签：
 * - 只允许不改变业务持久化状态的方法；
 * - events.subscribe 明确保留：它只建立订阅连接，不写数据库；维护期间事件 ingress
 *   由后续阶段单独暂停，不能因为允许订阅就认为事件仍会持续落库；
 * - recovery_locked / shutting_down 不适用本表，只允许 health/status。
 */
